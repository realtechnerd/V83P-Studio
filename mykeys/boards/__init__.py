"""Keyboard definitions. Each supported keyboard is a folder here with:

  board.json      name, USB IDs, layers, RGB effects, zones, firmware file
  layout.json     key + LED positions (generated by tools/gen_layout.py from the QMK definition)
  colorways.json  keycap colorways for the on-screen keyboard

Only the Inland MK PRO V2 is supported today. Adding a keyboard = adding a folder (plus, for per-key
colors / music mode, a firmware port with the MyKeys module).
"""
import json
from functools import cached_property
from pathlib import Path

BOARDS_DIR = Path(__file__).resolve().parent


class Board:
    def __init__(self, folder: Path):
        self.folder = folder
        self.info = json.loads((folder / "board.json").read_text(encoding="utf-8"))
        self.id = self.info["id"]
        self.name = self.info["name"]
        self.vid = int(self.info["usb"]["vid"], 16)
        self.pid = int(self.info["usb"]["pid"], 16)
        d = self.info.get("dongle")
        self.dongle = (int(d["vid"], 16), int(d["pid"], 16)) if d else None
        self.layout_path = folder / "layout.json"

    @cached_property
    def layout(self):
        return json.loads(self.layout_path.read_text(encoding="utf-8"))

    @cached_property
    def colorways(self):
        data = json.loads((self.folder / "colorways.json").read_text(encoding="utf-8"))
        return {k: v for k, v in data.items() if not k.startswith("_")}

    @property
    def effects(self):
        return {int(k): v for k, v in self.info["rgb"]["effects"].items()}

    @property
    def max_brightness(self):
        return self.info["rgb"]["max_brightness"]

    def public(self):
        """What the web UI needs to know about the board."""
        return {"id": self.id, "name": self.name, "short": self.info.get("short", self.name),
                "layers": self.info["layers"], "encoder": self.info.get("encoder", False),
                "colorways": self.colorways, "default_colorway": self.info.get("default_colorway")}


def load_all():
    return [Board(p) for p in sorted(BOARDS_DIR.iterdir()) if (p / "board.json").is_file()]


def find(vid, pid):
    return next((b for b in load_all() if (b.vid, b.pid) == (vid, pid)), None)


current = load_all()[0]  # the one supported board today
